--
-- 302 + 502 兩張圖純亮度漸層相鄰段太像、不易區分。改成「同一冷/暖系內
-- 小幅展開色相」,讓每段一眼看出差別,但仍在同一情緒家族。
--
-- 302 碳排部門結構  (6 系列, 暖系) → 紅褐 → 橘 → 琥珀 → 黃
-- 502 用電結構 donut (5 系列, 冷系) → 深綠 → 青綠 → teal → 藍 → 淺藍
--
-- Target: postgres-manager / dashboardmanager
-- 性質: idempotent
-- ============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- 302 碳排部門結構 (6 系列):暖系跨色相 - 每段易分但全暖
-- ---------------------------------------------------------------------------
UPDATE component_charts
SET color = '{#BF360C,#E65100,#FF6F00,#FFA726,#FFD54F,#FFF176}'
WHERE index = 'power_vs_emission_taipei';

-- ---------------------------------------------------------------------------
-- 502 用電結構 donut (5 系列):冷系跨色相 - 每段易分但全冷
-- ---------------------------------------------------------------------------
UPDATE component_charts
SET color = '{#1B5E20,#00695C,#00897B,#0288D1,#29B6F6}'
WHERE index = 'power_usage_ratio';

COMMIT;

-- ============================================================================
-- VERIFY
-- ============================================================================

\echo ''
\echo '=== updated palettes ==='
SELECT index, color
FROM component_charts
WHERE index IN ('power_vs_emission_taipei', 'power_usage_ratio')
ORDER BY index;
